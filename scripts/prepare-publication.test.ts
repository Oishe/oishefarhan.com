test("reads a bare index.md as this section's index, not the vault root", async () => {
  const vault = await withVault({
    // A root index.md must exist, or the ambiguity this pins down cannot arise.
    "index.md": note("Home", "publish: true\n", "Root."),
    "examples/index.md": note("Examples", "publish: true\n", "Section index."),
    "examples/one.md": note("One", "publish: true\n", "Back to [Examples](index.md)."),
  })

  const result = await vault.run()

  // This reading was Quartz's the other way round -- it collapsed a bare
  // index.md to the site root wherever it was written, which is why targets
  // used to be vault-absolute. Quarto reads it the way Obsidian does.
  assert.equal(result.published.length, 3)
})

