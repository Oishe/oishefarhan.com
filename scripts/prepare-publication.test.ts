test("rejects Obsidian syntax that Quarto would publish verbatim", async () => {
  const vault = await withVault({
    "notes/computed.qmd": note(
      "Computed",
      "publish: true\n",
      [
        "%%a note to self%%",
        "> [!note] Callout",
        "> Body.",
        "Some ==highlighted== text.",
      ].join("\n\n"),
    ),
  })

  const messages = await messagesFrom(() => vault.run())

  assert.equal(messages.length, 3)
  assert.match(messages.join("\n"), /comment syntax/)
  assert.match(messages.join("\n"), /callout/)
  assert.match(messages.join("\n"), /highlights/)
})

// Quarto callouts were rejected while a published .qmd was a body fragment with
// no Bootstrap behind it, which silently dropped the callout type. Quarto owns
// the chrome now, so Bootstrap is there and they are the supported form.
test("accepts Quarto callouts", async () => {
  const vault = await withVault({
    "notes/computed.qmd": note(
      "Computed",
      "publish: true\n",
      ['::: {.callout-note collapse="true"}', "## Title", "Body.", ":::"].join("\n\n"),
    ),
  })

  const result = await vault.run()

  assert.equal(result.published.length, 1)
})

test("rejects Obsidian-only syntax in Markdown too, not just Quarto", async () => {
  const vault = await withVault({
    "notes/prose.md": note(
      "Prose",
      "publish: true\n",
      "%%hidden%%\n\n> [!note] Callout\n> Body.\n\nSome ==highlighted== text.",
    ),
  })

  const messages = await messagesFrom(() => vault.run())

  // One renderer now, so .md has no dialect of its own to fall back on.
  assert.equal(messages.length, 3)
  assert.match(messages.join("\n"), /%%/)
  assert.match(messages.join("\n"), /callout/)
  assert.match(messages.join("\n"), /==text==/)
})

