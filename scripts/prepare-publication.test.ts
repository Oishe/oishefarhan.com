// Fixtures exercise a Python cell, a Jupyter widget and an Observable cell, and
// nothing in the portfolio does. So they must still be built, and must never
// reach the public site. The whole separation rests on one flag, which is why it
// is tested from both sides.
test("fixtures stay out of the production build", async () => {
  const vault = await withVault({
    "index.md": note("Home", "publish: true\n", "Real content."),
    "examples/fixture.md": note("Fixture", "publish: false\nfixture: true\n", "Bridge check."),
  })

  const result = await vault.run()

  assert.deepEqual(
    result.published.map((document) => document.slug),
    ["index"],
  )
  assert.doesNotMatch(
    await readFile(path.join(vault.vaultDir, "_quarto-publish.yml"), "utf8"),
    /fixture/,
  )
})

test("the validation build admits fixtures to the render list", async () => {
  const vault = await withVault({
    "index.md": note("Home", "publish: true\n", "Real content."),
    "examples/fixture.md": note("Fixture", "publish: false\nfixture: true\n", "Bridge check."),
  })

  const result = await vault.run({ includeFixtures: true, quartoProfile: "fixtures" })

  assert.deepEqual(
    result.published.map((document) => document.slug).sort(),
    ["examples/fixture", "index"],
  )
  // Its own output directory, so a fixture render can never write over the
  // tree the production build deploys.
  const profile = await readFile(path.join(vault.vaultDir, "_quarto-fixtures.yml"), "utf8")
  assert.match(profile, /examples\/fixture\.md/)
})

// A fixture that also claims `publish: true` would reach the site the moment
// someone ran the production build, which is the one thing this must prevent.
test("refuses a fixture that also claims to be published", async () => {
  const vault = await withVault({
    "examples/fixture.md": note("Fixture", "publish: true\nfixture: true\n", "Contradiction."),
  })

  const messages = await messagesFrom(() => vault.run())
  assert.ok(messages.some((message) => /must be `publish: false`/.test(message)))
})

// Quarto listings glob the filesystem rather than the project render list.
// Measured: an unpublished draft left in a listed folder was linked from the
